import { jsPDF } from 'jspdf'
import autoTable from 'jspdf-autotable'
import * as XLSX from 'xlsx'
import { wyndbase } from './wyndbase'

export type ExportFormat = 'csv' | 'xlsx' | 'pdf'
type Row = Record<string, unknown>

const cell = (v: unknown) => (v == null ? '' : typeof v === 'object' ? JSON.stringify(v) : String(v))

function download(blob: Blob, name: string) {
  const a = document.createElement('a')
  a.href = URL.createObjectURL(blob)
  a.download = name
  a.click()
  setTimeout(() => URL.revokeObjectURL(a.href), 1000)
}

/** Fetches the rows of one export through its audit.export* named query, which logs the export itself. */
export type ExportLoader = (format: ExportFormat) => Promise<readonly object[]>

/**
 * Exports a report as CSV, XLSX or PDF. The rows come from a server-side audit.export* named query that
 * reads them and writes the audit.export_log row (caller, format, row count, filters) in one statement,
 * so the app cannot produce an export file without a log row, nor log a row count of its own choosing.
 * Every file carries generated_by, generated_at and the filter criteria.
 */
export async function exportReport(reportName: string, title: string, load: ExportLoader, filters: Row, format: ExportFormat) {
  const rows = (await load(format)) as Row[]
  const me = await wyndbase.query.auth.getMe()
  const generatedBy = me[0]?.name || me[0]?.username || 'unknown'
  const generatedAt = new Date().toISOString()
  const cols = rows.length ? Object.keys(rows[0]).filter((c) => c !== '_id') : []
  const filterText = Object.entries(filters).filter(([, v]) => v !== '' && v != null).map(([k, v]) => `${k}=${v}`).join(', ') || 'none'

  const stamp = generatedAt.slice(0, 10)
  if (format === 'csv') {
    const esc = (v: unknown) => { const s = cell(v); return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s }
    const meta = [`# report,${esc(title)}`, `# generated_by,${esc(generatedBy)}`, `# generated_at,${generatedAt}`, `# filters,${esc(filterText)}`]
    const body = [cols.join(','), ...rows.map((r) => cols.map((c) => esc(r[c])).join(','))]
    download(new Blob([[...meta, ...body].join('\n')], { type: 'text/csv' }), `${reportName}-${stamp}.csv`)
    return
  }

  if (format === 'xlsx') {
    const wb = XLSX.utils.book_new()
    const data = XLSX.utils.json_to_sheet(rows.map((r) => Object.fromEntries(cols.map((c) => [c, numeric(r[c])]))), { header: cols })
    data['!cols'] = cols.map((c) => ({ wch: Math.min(40, Math.max(c.length, ...rows.map((r) => cell(r[c]).length)) + 2) }))
    XLSX.utils.book_append_sheet(wb, data, 'Report')
    const meta = XLSX.utils.aoa_to_sheet([['Report', title], ['Generated by', generatedBy], ['Generated at', generatedAt], ['Filters', filterText], ['Rows', rows.length]])
    meta['!cols'] = [{ wch: 14 }, { wch: 60 }]
    XLSX.utils.book_append_sheet(wb, meta, 'About')
    XLSX.writeFile(wb, `${reportName}-${stamp}.xlsx`)
    return
  }

  const doc = new jsPDF({ orientation: cols.length > 6 ? 'landscape' : 'portrait', unit: 'pt', format: 'a4' })
  doc.setFontSize(16)
  doc.text(`WynHR · ${title}`, 40, 44)
  doc.setFontSize(9)
  doc.setTextColor(110)
  doc.text(`Generated by ${generatedBy} at ${new Date(generatedAt).toLocaleString()} · Filters: ${filterText} · ${rows.length} rows`, 40, 62)
  autoTable(doc, {
    startY: 78,
    head: [cols],
    body: rows.map((r) => cols.map((c) => cell(r[c]))),
    styles: { fontSize: 8, cellPadding: 4 },
    headStyles: { fillColor: [30, 90, 55] },
    alternateRowStyles: { fillColor: [244, 246, 243] },
  })
  doc.save(`${reportName}-${stamp}.pdf`)
}

/** Decimals arrive as strings; write them to Excel as numbers so they can be summed. */
function numeric(v: unknown) {
  return typeof v === 'string' && /^-?\d+(\.\d+)?$/.test(v) ? Number(v) : v
}
